static_assert(sizeof(randomAddressFind) == sizeof(randomAddressReplace), "patch size");
// A controller may refuse legacy LE Create Connection (0x200d) once extended advertising
// commands are in use, and bluetoothd then restarts its stack after enough refusals. This
// turns on gEnableExtendedCreateConnectionCommand (0x2043): "movzbl slot, %edi" before its
